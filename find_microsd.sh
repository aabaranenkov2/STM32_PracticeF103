#!/bin/bash

# Скрипт для определения microSD карты в Linux

echo "════════════════════════════════════════════════════"
echo "  ПОИСК MICROSD КАРТЫ"
echo "════════════════════════════════════════════════════"
echo ""

echo "📋 Шаг 1: Список всех блочных устройств"
echo "────────────────────────────────────────────────────"
lsblk -o NAME,SIZE,TYPE,MOUNTPOINT,FSTYPE,LABEL
echo ""

echo "📋 Шаг 2: Последние сообщения ядра (новые устройства)"
echo "────────────────────────────────────────────────────"
echo "Ищем сообщения о подключении USB/SD устройств:"
dmesg | tail -20 | grep -i -E "(sd|usb|mmc)" | tail -10
echo ""

echo "📋 Шаг 3: Все диски и разделы"
echo "────────────────────────────────────────────────────"
sudo fdisk -l 2>/dev/null | grep -E "(Disk /dev/|/dev/sd)" | head -20
echo ""

echo "📋 Шаг 4: USB устройства"
echo "────────────────────────────────────────────────────"
lsusb | grep -i -E "(card|reader|storage|mass)"
echo ""

echo "════════════════════════════════════════════════════"
echo "  РЕКОМЕНДАЦИИ"
echo "════════════════════════════════════════════════════"
echo ""
echo "🔍 Как определить microSD:"
echo "   1. Посмотрите на размер в 'lsblk' - должен совпадать с вашей картой"
echo "   2. Обычно это /dev/sdb, /dev/sdc, /dev/mmcblk0 и т.д."
echo "   3. Если карта уже смонтирована, будет показан MOUNTPOINT"
echo ""
echo "💡 Примеры:"
echo "   • /dev/sdb1  - первый раздел на устройстве sdb"
echo "   • /dev/mmcblk0p1 - первый раздел на MMC устройстве"
echo ""
echo "⚠️  ВАЖНО:"
echo "   • Убедитесь, что выбрали правильное устройство!"
echo "   • Форматирование удалит все данные!"
echo ""

