#!/bin/bash

# Скрипт для диагностики кардридера и microSD

echo "════════════════════════════════════════════════════"
echo "  ДИАГНОСТИКА КАРДРИДЕРА И MICROSD"
echo "════════════════════════════════════════════════════"
echo ""

echo "📋 Шаг 1: Проверка USB устройств"
echo "────────────────────────────────────────────────────"
echo "Ищем кардридер в списке USB устройств:"
lsusb
echo ""

echo "📋 Шаг 2: Поиск кардридера по ключевым словам"
echo "────────────────────────────────────────────────────"
lsusb | grep -i -E "(card|reader|storage|mass|hub|chip)" || echo "Кардридер не найден в списке USB устройств"
echo ""

echo "📋 Шаг 3: Все блочные устройства (включая новые)"
echo "────────────────────────────────────────────────────"
lsblk -o NAME,SIZE,TYPE,MOUNTPOINT,FSTYPE,MODEL
echo ""

echo "📋 Шаг 4: Проверка USB устройств хранения"
echo "────────────────────────────────────────────────────"
ls -l /dev/sd* 2>/dev/null | head -10
echo ""

echo "📋 Шаг 5: Сообщения ядра (последние 50 строк)"
echo "────────────────────────────────────────────────────"
echo "Выполните вручную: sudo dmesg | tail -50"
echo "Или: sudo dmesg | grep -i 'usb\|sd\|mmc\|storage' | tail -30"
echo ""

echo "════════════════════════════════════════════════════"
echo "  ВОЗМОЖНЫЕ ПРОБЛЕМЫ И РЕШЕНИЯ"
echo "════════════════════════════════════════════════════"
echo ""
echo "❌ Проблема 1: Кардридер не виден в lsusb"
echo "   Решения:"
echo "   • Проверьте подключение USB (попробуйте другой порт)"
echo "   • Проверьте, что кардридер подключен напрямую (не через USB-хаб)"
echo "   • Попробуйте другой USB кабель (если есть)"
echo "   • Проверьте, что карта вставлена правильно"
echo ""
echo "❌ Проблема 2: Кардридер виден, но карта не определяется"
echo "   Решения:"
echo "   • Выньте и вставьте карту снова"
echo "   • Попробуйте другую карту (если есть)"
echo "   • Проверьте, что карта не заблокирована (переключатель на карте)"
echo "   • Проверьте формат карты (может быть повреждена)"
echo ""
echo "❌ Проблема 3: Нужны драйверы"
echo "   Решения:"
echo "   • Ubuntu обычно автоматически определяет кардридеры"
echo "   • Попробуйте: sudo modprobe usb_storage"
echo "   • Проверьте: lsmod | grep usb_storage"
echo ""
echo "❌ Проблема 4: Кардридер несовместим"
echo "   Решения:"
echo "   • Некоторые дешевые кардридеры работают только с Windows"
echo "   • Попробуйте другой кардридер (если есть)"
echo "   • Проверьте отзывы о модели DEXP RL-02 для Linux"
echo ""

echo "════════════════════════════════════════════════════"
echo "  КОМАНДЫ ДЛЯ РУЧНОЙ ПРОВЕРКИ"
echo "════════════════════════════════════════════════════"
echo ""
echo "1. Проверить USB устройства:"
echo "   lsusb"
echo ""
echo "2. Проверить сообщения ядра (требует sudo):"
echo "   sudo dmesg | tail -50"
echo ""
echo "3. Принудительно загрузить модуль USB storage:"
echo "   sudo modprobe usb_storage"
echo ""
echo "4. Проверить, загружен ли модуль:"
echo "   lsmod | grep usb_storage"
echo ""
echo "5. Проверить все блочные устройства:"
echo "   lsblk"
echo ""
echo "6. Проверить USB устройства хранения:"
echo "   ls -l /dev/sd*"
echo ""

